class Oracle:
    def __init__(self, generated: Path):
        import generate_v3_fuzzer_golden as g  # noqa: PLC0415

        self.g = g
        g.bootstrap(generated)
        import checkpoint_store  # noqa: PLC0415
        import fuzzer_training  # noqa: PLC0415
        from common import canonical, digest  # noqa: PLC0415
        from privoke_contracts import classification  # noqa: PLC0415
        from privoke_model import v3_contract as contract  # noqa: PLC0415
        from src import classification as production  # noqa: PLC0415

        self.store_module, self.fuzzer_training = checkpoint_store, fuzzer_training
        self.canonical, self.digest, self.contract = canonical, digest, contract
        self.synthesis = g.Synthesis(contract, canonical, digest, classification, production)
        self.scratch = tempfile.TemporaryDirectory(ignore_cleanup_errors=True)
        self.input_root = g.prepare_input_root(Path(self.scratch.name))
        # The store validates the source with the default repository root; point it at the committed pinned inputs.
        original = fuzzer_training.validate_schedule
        root = self.input_root
        fuzzer_training.validate_schedule = lambda training, guard, source, policy, input_root=root: original(training, guard, source, policy, input_root)
        os.environ["V3_AUDIENCE_MANIFEST_PATH"] = str(g.FIXTURES / "au3" / "audience-v3-manifest-v1.json")
        os.environ["V3_AUDIENCE_MANIFEST_SHA256"] = g.AU3_RELEASE_SHA256

    def source(self, sampler: str, seed: int, policy: dict) -> dict:
        _, _, source = self.fuzzer_training.schedule(seed, policy, self.input_root, sampler=sampler)
        return source


