"""Golden generator for the Rust V3 checkpoint store (`rust/services/param-update/src/v3_store`, stage V3-R1).

The oracle is the maintained, unchanged Python `services/pretrained-v3/src/checkpoint_store.py`, run in process on the host over
a scripted sequence of operations: bootstrap, resolve, stage (evidence and candidate), commit and status. Every refusal of
`admit_candidate` and of the transactional commit is provoked on purpose (lineage, provenance, inventory, tensor bytes, evidence
identity, reported changes, HEADS changing non-heads tensors, a tampered source record, a stale base, a guard rejection, a request
id reused with the same and with different content, a missing blob), and the outcome and the reason of each step are recorded,
together with the catalog after it (the blobs, the `current` table and the `receipts` table, byte for byte).

The package is synthetic and small in everything but its tensor count: the manifest contract pins the parameter count of the real
tiers (`efficient` 4,785,044 and `balanced` 9,596,180), so each ORIGINAL and candidate weights file is that many float32 values,
generated by a closed-form function of (salt, index) that the Rust test reproduces. The official `config.json` and `vocab.txt` are
admitted by SHA-256, so the public files themselves are the fixtures (`rust/services/param-update/tests/fixtures/v3_store`).
The sources of the fits are the committed pinned BC01 inputs and the AU3 release of `rust/crates/privoke-curriculum`. The golden
holds no prompt text: evidence documents are recorded without their `source` member, which the Rust test regenerates from the
pinned inputs (the SHA-256 of every evidence document is recorded and checked).

Usage (host Python, for example `evaluation/.venv-v1-v3-pipeline`; `--generated` or `PRIVOKE_GENERATED` names the generated
protobuf clients, a directory holding `privoke/v1` and `privoke/experimental`):

  python evaluation/generate_checkpoint_store_golden.py --generated <dir>

Output: `rust/services/param-update/tests/fixtures/v3_checkpoint_store_golden.json`.
"""
