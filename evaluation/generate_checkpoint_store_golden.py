BC01, AU3 = "existing_taxonomy_benign_common_frozen_stream_v1", "audience_common_frozen_stream_v1"


def original_of(oracle: Oracle, layout: str):
    package = Package(Recipe(layout))
    document = manifest_of(oracle, package, scope="original")
    raw = oracle.canonical(document)
    return package, raw, oracle.digest(raw)


def story_lifecycle(oracle: Oracle, golden: dict):
    """Admit, stage and commit on BC01 sources: the whole life of a model's versions, one refusal per rule."""
    d = Driver(oracle, golden, "bc01-lifecycle")
    orig, orig_raw, m0 = original_of(oracle, "efficient")
    base_recipe = orig.recipe

    def fit(rid, parent_sha, parent_pkg, scope, recipe, seed, **kwargs):
        return Fit(oracle, tier="efficient", scope=scope, request_id=rid, parent_sha=parent_sha, parent=parent_pkg, recipe=recipe,
                   sampler=BC01, seed=seed, original_sha=m0, **kwargs)

    d.status("never-issued")
    d.resolve(EFFICIENT)
    d.bootstrap("efficient", orig, orig_raw)
    d.resolve(EFFICIENT)
    d.resolve(BALANCED)
    d.bootstrap("again", orig, orig_raw)  # idempotent: the model keeps its version

    # A first HEADS version, from the ORIGINAL.
    f1 = fit("v3-life-heads-1", m0, orig, "heads", base_recipe.derive(heads__weight=11, heads__bias=12), 42)
    d.stage_candidate(f1, "a candidate before its evidence is staged")
    d.stage_evidence(f1)
    d.stage_evidence(f1)  # the same object again
    d.stage_candidate(f1)
    d.commit(f1)
    d.commit(f1, "the same commit again answers from its receipt")
    d.commit(f1, "the same request id with other content", expected_base=sha(b"another base"))
    d.status(f1.request_id)
    d.resolve(EFFICIENT)
    p1 = f1.child

    # Two fits from the same base race: the first wins, the second sees a stale base.
    f2 = fit("v3-life-heads-2", f1.manifest_sha, p1, "heads", p1.recipe.derive(heads__weight=21), 43)
    f3 = fit("v3-life-heads-3", f1.manifest_sha, p1, "heads", p1.recipe.derive(heads__bias=31), 44)
    for item in (f2, f3):
        d.stage_evidence(item)
        d.stage_candidate(item)
    d.commit(f2)
    d.commit(f3, "a stale base is rejected, not an error")
    d.commit(f3, "the rejection is idempotent")
    d.status(f3.request_id)
    p2 = f2.child

    # A candidate that regresses the guard, and one that is both stale and regressing.
    f4 = fit("v3-life-regress-1", f2.manifest_sha, p2, "heads", p2.recipe.derive(heads__weight=41), 45, quality="regresses")
    d.stage_evidence(f4)
    d.stage_candidate(f4)
    d.commit(f4, "a guard failure is rejected")
    f5 = fit("v3-life-regress-2", f1.manifest_sha, p1, "heads", p1.recipe.derive(heads__bias=51), 46, quality="regresses")
    d.stage_evidence(f5)
    d.stage_candidate(f5)
    d.commit(f5, "a stale base is reported before the guard")

    # Identity of the commit against the candidate and its evidence.
    d.commit(f4, "an expected base that is not the candidate's parent", request_id="v3-life-identity-1", expected_base=f1.manifest_sha)
    d.commit(f4, "another model than the candidate's", request_id="v3-life-identity-2", model_id=BALANCED)
    d.commit(f4, "another request id than the evidence's", request_id="v3-life-identity-3")
    d.commit(f4, "another evidence than the manifest's", request_id=f4.request_id + "-e", evidence=f1.evidence_sha)
    d.commit(f4, "an empty request id", request_id="")
    d.commit(f4, "an unbounded request id", request_id="x" * 201)
    d.commit(f4, "a digest that is not lowercase hexadecimal", expected_base="NOT-A-DIGEST")
    d.commit(f4, "a candidate that was never staged", request_id="v3-life-missing", candidate=sha(b"never staged"))

    # A FULL_ENCODER version: every tensor group changes.
    full_recipe = p2.recipe.derive(**{"encoder__embeddings__word_embeddings__weight": 61, "encoder__encoder__layer__0__weight": 62,
                                      "encoder__encoder__layer__1__weight": 63, "encoder__encoder__layer__2__weight": 64,
                                      "encoder__encoder__layer__3__weight": 65, "encoder__pooler__bias": 66, "encoder__pooler__weight": 67,
                                      "heads__bias": 68, "heads__weight": 69})
