def b64(raw: bytes) -> str:
    return base64.b64encode(raw).decode("ascii")


def sha(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


# ---------------------------------------------------------------------------------------------------------------------------
# The synthetic weights: a closed-form function of (salt, index), reproduced by the Rust test.
# ---------------------------------------------------------------------------------------------------------------------------


def values(salt: int, count: int) -> np.ndarray:
    index = np.arange(count, dtype=np.uint64)
    x = index * np.uint64(0x9E3779B97F4A7C15) + np.uint64((salt * 0xD1B54A32D192ED03) & MASK64)
    x ^= x >> np.uint64(29)
    x = x * np.uint64(0xBF58476D1CE4E5B9)
    x ^= x >> np.uint64(32)
    return (x & np.uint64(0xFFFF)).astype(np.float32) / np.float32(65536.0) - np.float32(0.5)


class Recipe:
    """One weights file: an inventory, a salt per tensor (a default and overrides) and optionally one NaN."""

    def __init__(self, layout: str, default: int = 1, overrides: dict | None = None, nan: str | None = None):
        self.layout, self.default, self.overrides, self.nan = layout, default, dict(overrides or {}), nan
        self._tensors = None

    def derive(self, **overrides) -> "Recipe":
        merged = dict(self.overrides)
        merged.update({name.replace("__", "."): salt for name, salt in overrides.items()})
        return Recipe(self.layout, self.default, merged, self.nan)

    def variant(self, layout: str | None = None, nan: str | None = None, **overrides) -> "Recipe":
        """The same salts over another inventory, or with one NaN."""
        merged = dict(self.overrides)
        merged.update({name.replace("__", "."): salt for name, salt in overrides.items()})
        return Recipe(layout or self.layout, self.default, merged, nan or self.nan)

    def spec(self) -> dict:
        return {"layout": self.layout, "default": self.default, "overrides": dict(sorted(self.overrides.items())), "nan": self.nan}

    def tensors(self) -> dict:
        if self._tensors is None:
            result = {}
            for name, shape in LAYOUTS[self.layout]:
                array = values(self.overrides.get(name, self.default), int(np.prod(shape)))
                if name == self.nan:
                    array.view(np.uint32)[0] = 0x7FC00000
                result[name] = array.astype("<f4").tobytes()
            self._tensors = result
        return self._tensors

    def safetensors(self) -> bytes:
        header, offset, body = {}, 0, []
        for name, shape in LAYOUTS[self.layout]:
            raw = self.tensors()[name]
            header[name] = {"dtype": "F32", "shape": shape, "data_offsets": [offset, offset + len(raw)]}
            offset += len(raw)
            body.append(raw)
        encoded = json.dumps(header, separators=(",", ":")).encode()
        encoded += b" " * ((8 - len(encoded) % 8) % 8)
        return struct.pack("<Q", len(encoded)) + encoded + b"".join(body)


class Package:
    """A recipe with its blob, its digests and its manifest inventory."""

    def __init__(self, recipe: Recipe):
        self.recipe = recipe
        self.blob = recipe.safetensors()
        self.blob_sha = sha(self.blob)
        self.inventory = {name: {"dtype": "F32", "shape": shape, "sha256": sha(recipe.tensors()[name])} for name, shape in LAYOUTS[recipe.layout]}


