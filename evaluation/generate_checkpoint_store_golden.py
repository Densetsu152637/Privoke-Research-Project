def story_catalog(oracle: Oracle, golden: dict):
    """Two models in one catalog, refused bootstraps, and a lineage that crosses tiers."""
    d = Driver(oracle, golden, "two-tiers")
    eff, eff_raw, m_eff = original_of(oracle, "efficient")
    bal, bal_raw, m_bal = original_of(oracle, "balanced")
    wrong_config = {"b64": b64(b"{}\n")}
    d.bootstrap("an asset that is not the pinned config", eff, eff_raw, config=wrong_config)
    d.resolve(EFFICIENT)
    candidate_manifest = oracle.canonical(manifest_of(oracle, eff, scope="heads", parent=m_eff, original=m_eff, evidence=sha(b"no evidence")))
    d.bootstrap("a manifest that is not an ORIGINAL", eff, candidate_manifest)
    d.bootstrap("efficient", eff, eff_raw)
    d.bootstrap("balanced", bal, bal_raw)
    d.resolve(EFFICIENT)
    d.resolve(BALANCED)
    # An efficient candidate whose parent is the balanced ORIGINAL.
    crossing = Fit(oracle, tier="efficient", scope="heads", request_id="v3-cross-1", parent_sha=m_bal, parent=bal, original_sha=m_bal,
                   recipe=eff.recipe.derive(heads__bias=121), sampler=BC01, seed=42, measured=eff)
    d.stage_evidence(crossing)
    d.stage_candidate(crossing, "a parent of another tier")
    d.close()


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--generated", type=Path, default=os.environ.get("PRIVOKE_GENERATED"),
                        help="directory with the generated protobuf clients (privoke/v1 and privoke/experimental)")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)
    if args.generated is None:
        parser.error("--generated or PRIVOKE_GENERATED is required")
    sys.path.insert(0, str(EVALUATION))
    oracle = Oracle(Path(args.generated))
    golden = {"schema": 1, "oracle": "services/pretrained-v3/src/checkpoint_store.py", "python": sys.version.split()[0],
              "numpy": np.__version__, "layouts": {name: [[tensor, shape] for tensor, shape in layout] for name, layout in LAYOUTS.items()},
              "blobs": {}, "documents": {}, "evidence": {}, "stories": []}
    for story in (story_lifecycle, story_audience, story_catalog):
        story(oracle, golden)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(golden, indent=1, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    steps = [step for story in golden["stories"] for step in story["steps"]]
    summary = {"stories": len(golden["stories"]), "steps": len(steps), "blobs": len(golden["blobs"]), "evidence": len(golden["evidence"]),
               "ok": sum("ok" in step["outcome"] for step in steps), "errors": sum("error" in step["outcome"] for step in steps)}
    reasons = {}
    for step in steps:
        if step["op"] == "commit" and "ok" in step["outcome"]:
            key = step["outcome"]["ok"]["status"] + ":" + step["outcome"]["ok"]["reason"]
            reasons[key] = reasons.get(key, 0) + 1
    summary["commit_outcomes"] = reasons
    summary["error_messages"] = sorted({str(step["outcome"]["error"]["class"]) + ": " + str(step["outcome"]["error"]["message"])
                                         for step in steps if "error" in step["outcome"]})
    print(json.dumps({**summary, "output": str(args.output)}, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
