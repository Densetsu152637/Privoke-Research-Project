def manifest_of(oracle: Oracle, package: Package, *, scope: str, parent: str = "", original: str = "", evidence: str = "", **changes) -> dict:
    contract = oracle.contract
    tier = TIER_OF_LAYOUT[package.recipe.layout]
    spec = contract.TIERS[tier]
    weights, config = contract.SOURCE_PINS[tier]
    document = {"schema": 1, "architecture": contract.ARCHITECTURE, "model_id": "privoke-v3-" + tier, "tier": tier, "parent": parent,
                "original": original, "blob": package.blob_sha, "config": config, "vocab": contract.VOCAB_SHA256,
                "source": {"repository": spec["repository"], "revision": spec["revision"], "weights_sha256": weights,
                           "config_sha256": config, "vocab_sha256": contract.VOCAB_SHA256},
                "tensors": package.inventory, "parameter_count": spec["parameters"], "scope": scope, "evidence": evidence}
    document.update(changes)
    return document


def evidence_of(oracle: Oracle, *, tier: str, scope: str, request_id: str, base: str, candidate_blob: str, parent: Package, child: Package,
                source: dict, source_commitment: str, policy: dict, quality: str, targets=None, parity: bool = True) -> dict:
    contract, synthesis = oracle.contract, oracle.synthesis
    spec = contract.TIERS[tier]
    full = scope == "full_encoder"
    layers = spec["num_hidden_layers"]
    steps, rows, micro = policy["steps"], policy["batch_rows"], policy["microbatch"]
    microbatches = steps * rows // micro
    own = [row["packed_target"] for row in source["guard_sidecar"]]
    targets = own if targets is None else targets
    others = [targets[(index + 5) % len(targets)] for index in range(len(targets))]
    right, wrong = list(targets), [others[i] if i % 2 == 0 else targets[i] for i in range(len(targets))]
    if quality == "improves":
        base_predictions, candidate_predictions = [others[i] if i % 3 == 0 else targets[i] for i in range(len(targets))], right
    else:
        base_predictions, candidate_predictions = right, wrong
    confidence = [0.9] * len(targets)
    base_guard = synthesis.guard(targets, base_predictions, confidence)
    candidate_guard = synthesis.guard(targets, candidate_predictions, confidence)
    harms = sum(any(max(0, d * (b["action_value"] - b["target_action_value"])) > max(0, d * (a["action_value"] - a["target_action_value"]))
                    for d in (-1, 1)) for a, b in zip(base_guard["rows"], candidate_guard["rows"]))
    counts = {"optimizer_steps": steps, "train_rows": steps * rows, "microbatch_forward": microbatches, "microbatch_backward": microbatches,
              "encoder_block_forward": microbatches * layers, "encoder_block_backward": microbatches * layers if full else 0}
    changed, changes = contract.tensor_changes(parent.inventory, child.inventory, layers)
    return {
        "schema": 1, "model_id": "privoke-v3-" + tier, "tier": tier, "request_id": request_id, "base": base, "scope": scope, "layers": [4],
        "source_commitment": source_commitment, "policy": policy, "train_wire_sha256": source["train_wire_sha256"],
        "guard_wire_sha256": source["guard_wire_sha256"],
        "phases": {"training": {"layer": 4, "status": "ok", "examples": steps * rows},
                   "base_heldout": {"layer": 4, "status": "ok", "examples": policy["guard_rows"]},
                   "candidate_heldout": {"layer": 4, "status": "ok", "examples": policy["guard_rows"]}},
        "base_guard": base_guard, "candidate_guard": candidate_guard, "action_harms": harms, "changes": changes, "changed_tensors": changed,
        "counts": counts, "block_counts": {"forward": [microbatches] * layers, "backward": [microbatches if full else 0] * layers},
        "losses": [round(1.0 / (step + 1), 6) for step in range(steps)],
        "gradient_trace": [{"step": step + 1, "norm_before_clip": 0.5 + step / 100, "encoder_nonzero_gradients": 3 if full and step else 0}
                           for step in range(steps)],
        "parameter_count": spec["parameters"], "trainable_count": spec["parameters"] if full else 20 * (spec["hidden_size"] + 1),
        "device": "cpu", "torch": "synthetic-oracle", "seconds": 0.5, "cuda_peak_bytes": 0,
        "candidate_blob": candidate_blob, "serialized_guard_parity": parity,
    }


def set_path(document, path, value):
    for key in path[:-1]:
        document = document[key]
    document[path[-1]] = value


class Fit:
    """What a V3 runtime would have produced for one request, built to order (with optional tampering)."""

    def __init__(self, oracle: Oracle, *, tier: str, scope: str, request_id: str, parent_sha: str, parent: Package, recipe: Recipe,
                 sampler: str, seed: int, quality: str = "improves", edits=None, recommit: bool = False, targets=None, parity: bool = True,
                 evidence_base=None, evidence_scope=None, original_sha: str, manifest_changes=None, claim_original: bool = False,
                 manifest_parent=None, measured: Package | None = None, rotate_targets: bool = False):
        self.oracle, self.request_id, self.tier, self.scope = oracle, request_id, tier, scope
        policy = oracle.g.frozen_policy(2)
        clean = oracle.source(sampler, seed, policy)
        commitment = oracle.digest(oracle.canonical(clean))
        source = copy.deepcopy(clean)
        for path, value in edits or []:
            set_path(source, path, value)
        if edits and recommit:
            commitment = oracle.digest(oracle.canonical(source))
        self.child = Package(recipe)
        if rotate_targets:
            own = [row["packed_target"] for row in clean["guard_sidecar"]]
            targets = own[3:] + own[:3]
            assert targets != own
        evidence = evidence_of(oracle, tier=tier, scope=evidence_scope or scope, request_id=request_id, base=evidence_base or parent_sha,
                               candidate_blob=self.child.blob_sha, parent=measured or parent, child=self.child, source=clean,
                               source_commitment=commitment, policy=policy, quality=quality, targets=targets, parity=parity)
        self.evidence_doc = dict(evidence, source=source)
        self.evidence_bytes = oracle.canonical(self.evidence_doc)
        self.evidence_sha = oracle.digest(self.evidence_bytes)
        skeleton = dict(evidence)
        self.record = {"skeleton_b64": b64(oracle.canonical(skeleton)), "sampler": sampler, "seed": seed, "policy_steps": 2,
                       "source_hashes": source["source_hashes"], "edits": [[path, value] for path, value in edits or []]}
        document = manifest_of(oracle, self.child, scope="original" if claim_original else scope,
                               parent="" if claim_original else (manifest_parent or parent_sha),
                               original="" if claim_original else original_sha,
                               evidence="" if claim_original else self.evidence_sha)
        document.update(manifest_changes or {})
        self.manifest_doc = document
        self.manifest_bytes = oracle.canonical(document)
        self.manifest_sha = oracle.digest(self.manifest_bytes)
        self.parent_sha, self.parent = parent_sha, parent

    def commit_request(self, **overrides) -> dict:
        request = {"request_id": self.request_id, "model_id": "privoke-v3-" + self.tier, "expected_base": self.parent_sha,
                   "candidate": self.manifest_sha, "evidence": self.evidence_sha}
        request.update(overrides)
        return request


# ---------------------------------------------------------------------------------------------------------------------------
# The driver: one store, its steps and the catalog after each of them.
# ---------------------------------------------------------------------------------------------------------------------------


class Driver:
    def __init__(self, oracle: Oracle, golden: dict, name: str):
        self.oracle, self.golden, self.name = oracle, golden, name
        self.scratch = tempfile.TemporaryDirectory(ignore_cleanup_errors=True)
        self.directory = Path(self.scratch.name) / "store"
        self.store = oracle.store_module.CheckpointStore(self.directory)
        self.steps = []
        golden["stories"].append({"name": name, "steps": self.steps})

    def close(self):
        self.store.db.close()

    # recording ------------------------------------------------------------------------------------------------------------

    def snapshot(self) -> dict:
        connection = sqlite3.connect(self.directory / "catalog.sqlite")
        try:
            current = {model: manifest for model, manifest in connection.execute("SELECT model,manifest FROM current ORDER BY model")}
            receipts = [[identity, fingerprint, b64(bytes(payload))]
                        for identity, fingerprint, payload in connection.execute("SELECT id,fingerprint,payload FROM receipts ORDER BY id")]
        finally:
            connection.close()
        blobs = sorted(path.name for path in (self.directory / "blobs").iterdir() if not path.name.startswith("stage-"))
        return {"blobs": blobs, "current": current, "receipts": receipts}

    def run(self, step: dict, call):
        try:
            result = call()
            step["outcome"] = {"ok": result}
        except Exception as error:  # noqa: BLE001 - every refusal of the oracle is a recorded outcome
            step["outcome"] = {"error": {"class": type(error).__name__, "message": str(error) if type(error) is ValueError else None}}
        step["after"] = self.snapshot()
        self.steps.append(step)
        return step["outcome"]

    # documents ------------------------------------------------------------------------------------------------------------

    def blob(self, package: Package) -> str:
        self.golden["blobs"].setdefault(package.blob_sha, package.recipe.spec())
        return package.blob_sha

    def document(self, raw: bytes) -> str:
        key = sha(raw)
        self.golden["documents"].setdefault(key, b64(raw))
        return key

    def evidence(self, fit: Fit) -> str:
        self.golden["evidence"].setdefault(fit.evidence_sha, fit.record)
        return fit.evidence_sha

    # operations -----------------------------------------------------------------------------------------------------------

    def bootstrap(self, label: str, package: Package, manifest_raw: bytes, *, config: dict | None = None, vocab: dict | None = None):
        config = config or {"fixture": "config-" + TIER_OF_LAYOUT[package.recipe.layout] + ".json"}
        vocab = vocab or {"fixture": "vocab.txt"}
        step = {"op": "bootstrap", "label": label, "manifest": self.document(manifest_raw), "blob": self.blob(package), "config": config, "vocab": vocab}

        def call():
            directory = Path(self.scratch.name) / ("initial-" + label)
            directory.mkdir(parents=True, exist_ok=True)
            (directory / "manifest.json").write_bytes(manifest_raw)
            (directory / "model.safetensors").write_bytes(package.blob)
            (directory / "config.json").write_bytes(asset(config))
            (directory / "vocab.txt").write_bytes(asset(vocab))
            self.store.bootstrap(directory)
            return None

        return self.run(step, call)

    def resolve(self, model: str):
        return self.run({"op": "resolve", "model": model}, lambda: self.store.resolve(model))

    def status(self, request_id: str):
        def call():
            answer = self.store.status(request_id)
            return {key: answer.get(key, "") for key in ("status", "request_id", "model_id", "base", "candidate", "reason")}

        return self.run({"op": "status", "request_id": request_id}, call)

    def stage_evidence(self, fit: Fit):
        step = {"op": "stage", "label": "evidence of " + fit.request_id, "payload": {"evidence": self.evidence(fit)}, "manifest": None}
        return self.run(step, lambda: self.store.stage(fit.evidence_bytes, b""))

    def stage_raw(self, label: str, payload: dict, manifest: dict | None, raw_payload: bytes, raw_manifest: bytes):
        return self.run({"op": "stage", "label": label, "payload": payload, "manifest": manifest}, lambda: self.store.stage(raw_payload, raw_manifest))

    def stage_candidate(self, fit: Fit, label: str | None = None):
        payload = {"blob": self.blob(fit.child)}
        manifest = {"document": self.document(fit.manifest_bytes)}
        return self.stage_raw(label or "candidate of " + fit.request_id, payload, manifest, fit.child.blob, fit.manifest_bytes)

    def commit(self, fit: Fit, label: str | None = None, **overrides):
        return self.commit_request(label or "commit " + fit.request_id, fit.commit_request(**overrides))

    def commit_request(self, label: str, request: dict):
        def call():
            receipt = self.store.commit(types.SimpleNamespace(**request))
            return {key: receipt.get(key, "") for key in ("status", "request_id", "model_id", "base", "candidate", "reason")}

        return self.run({"op": "commit", "label": label, "request": request}, call)


def asset(description: dict) -> bytes:
    if "fixture" in description:
        return (FIXTURE_DIR / description["fixture"]).read_bytes()
    return base64.b64decode(description["b64"])


